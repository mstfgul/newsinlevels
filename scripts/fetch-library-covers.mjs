#!/usr/bin/env node
/**
 * fetch-library-covers.mjs — the Library shelf's covers (ST-104).
 *
 *   PATH=/usr/local/bin:$PATH node scripts/fetch-library-covers.mjs
 *
 * Reads the app's public library manifest (Firebase Storage,
 * library/index.json — public read), keeps only the Standard Ebooks titles
 * (their covers are CC0 — SE dedicates all its files to the public domain;
 * books added later through the studio may carry publisher covers, so they
 * are NOT taken), downloads each cover once and encodes a 480px WebP into
 * public/library/, then writes lib/library.ts. Idempotent.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "library");
const MANIFEST = path.join(ROOT, "lib", "library.ts");
const INDEX_URL =
  "https://firebasestorage.googleapis.com/v0/b/anytext-c8f72.firebasestorage.app/o/library%2Findex.json?alt=media";
/** Standard Ebooks titles in the app (public-domain text, CC0 covers). */
const STANDARD_EBOOKS = new Set([
  "alice",
  "notes-from-underground",
  "gatsby",
  "call-of-the-wild",
  "washington-square",
  "pierre-and-jean",
]);
const WIDTH = 480;

const res = await fetch(INDEX_URL, { headers: { "User-Agent": "AnyTextWeb/1.0 (https://anytext.art)" } });
if (!res.ok) throw new Error(`index.json ${res.status}`);
const index = await res.json();
await mkdir(OUT_DIR, { recursive: true });
const books = [];
for (const b of index.books) {
  if (!STANDARD_EBOOKS.has(b.id)) continue;
  const out = path.join(OUT_DIR, `${b.id}.webp`);
  if (!existsSync(out)) {
    const cover = await fetch(b.cover);
    if (!cover.ok) throw new Error(`${b.id}: cover ${cover.status}`);
    await sharp(Buffer.from(await cover.arrayBuffer()))
      .resize({ width: WIDTH, withoutEnlargement: true })
      .webp({ quality: 82 })
      .toFile(out);
  }
  const meta = await sharp(out).metadata();
  const title = typeof b.title === "string" ? b.title : b.title?.en ?? b.id;
  books.push({ id: b.id, title, author: b.author, year: String(b.year), chapters: b.chapters, width: meta.width, height: meta.height });
  console.log(`ok   ${b.id.padEnd(24)} ${meta.width}×${meta.height}  ${title} — ${b.author}`);
}
books.sort((a, b) => Number(a.year) - Number(b.year));
const rows = books
  .map(
    (b) =>
      `  { id: ${JSON.stringify(b.id)}, title: ${JSON.stringify(b.title)}, author: ${JSON.stringify(b.author)}, year: ${JSON.stringify(b.year)}, chapters: ${b.chapters}, width: ${b.width}, height: ${b.height} },`,
  )
  .join("\n");
await writeFile(
  MANIFEST,
  `/**
 * GENERATED by scripts/fetch-library-covers.mjs — do not edit by hand.
 * The app's Library, as shown on the homepage shelf: Standard Ebooks titles
 * (public-domain text; covers CC0), every chapter rewritten at six levels.
 */
export interface LibraryBook {
  id: string;
  title: string;
  author: string;
  year: string;
  chapters: number;
  width: number;
  height: number;
}

export const LIBRARY: readonly LibraryBook[] = [
${rows}
] as const;

export const bookCoverSrc = (b: LibraryBook) => \`/library/\${b.id}.webp\`;
`,
);
console.log(`${books.length} books → lib/library.ts`);
